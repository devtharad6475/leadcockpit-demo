test('USD quote drawer refreshes status and shows the saved currency throughout', async ({ page, request }) => {
  const leadId = data().leads[0].id;
  const result = await request.post('/api/quotes', { headers, data: { leadId, currencyCode: 'USD', lineItems: [{ productName: 'Export thread', quantity: 2, unitPrice: 12.345 }] } });
  expect(result.ok()).toBe(true); const q: Quote = await result.json();
  expect(q.grandTotal).toBe(24.69);
  await loginDemo(page); await openTabByLabel(page, 'Quotes & Orders');
  await page.getByRole('tab', { name: /Quotes/ }).click();
  await page.getByRole('button', { name: `View details for quote #${q.quoteNumber}`, exact: true }).click();
  let drawer = page.getByRole('dialog', { name: `Quote #${q.quoteNumber}`, exact: true });
  await expect(drawer).toContainText('$24.69'); await expect(drawer).toContainText('$12.345');
  await expect(drawer).not.toContainText('₹');
  await drawer.getByLabel('Update quote status').selectOption('sent');
  await expect(page.getByRole('dialog', { name: `Quote #${q.quoteNumber}`, exact: true }).getByText('Sent', { exact: true })).toBeVisible();
  drawer = page.getByRole('dialog', { name: `Quote #${q.quoteNumber}`, exact: true });
  await expect(drawer.getByLabel('Update quote status').locator('option[value="sent"]')).toHaveCount(0);
  await page.screenshot({ path: `${proof}/week-three-usd-quote.png`, fullPage: true });
  expect(data().quotes?.find(row => row.id === q.id)?.status).toBe('sent');
  await page.reload(); await openTabByLabel(page, 'Quotes & Orders'); await page.getByRole('tab', { name: /Quotes/ }).click();
  await page.getByRole('button', { name: `View details for quote #${q.quoteNumber}`, exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Sent', { exact: true })).toBeVisible();
});

test('UI revision keeps the old quote and conversion creates exactly one linked order', async ({ page, request }) => {
  const result = await request.post('/api/quotes', { headers, data: { leadId: data().leads[0].id, lineItems: [{ productName: 'Revision thread', quantity: 3, unitPrice: 101.015 }], validityNote: 'Seven days' } });
  expect(result.ok()).toBe(true); const q: Quote = await result.json(); expect(q.grandTotal).toBe(303.05);
  await loginDemo(page); await openTabByLabel(page, 'Quotes & Orders'); await page.getByRole('tab', { name: /Quotes/ }).click();
  await page.getByRole('button', { name: `More actions for quote #${q.quoteNumber}`, exact: true }).click();
  const revisionResponse = page.waitForResponse(r => r.url().endsWith(`/api/quotes/${q.id}/revise`));
  await page.getByRole('menuitem', { name: 'Revise (replace with new quote)' }).click();
  await page.getByRole('button', { name: 'Save revised quote', exact: true }).click();
  const revision = await revisionResponse; expect(revision.ok()).toBe(true); const { quote: replacement } = await revision.json();
  expect(replacement.supersedesQuoteId).toBe(q.id); expect(replacement.grandTotal).toBe(303.05);
  expect(data().quotes?.find(row => row.id === q.id)?.status).toBe('superseded');
  await expect(page.getByRole('dialog', { name: `Quote #${replacement.quoteNumber}`, exact: true })).toBeVisible();
  await page.getByLabel('Update quote status').selectOption('sent');
  await expect(page.getByRole('dialog').getByText('Sent', { exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: /Close/ }).click();
  await page.getByRole('button', { name: `More actions for quote #${replacement.quoteNumber}`, exact: true }).click();
  await page.getByRole('menuitem', { name: 'Convert to order', exact: true }).click();
  const convertedResponse = page.waitForResponse(r => r.url().endsWith(`/api/quotes/${replacement.id}/convert`));
  await page.getByRole('dialog', { name: 'Convert this quote?' }).getByRole('button', { name: 'Convert to order', exact: true }).click();
  const converted = await convertedResponse; expect(converted.ok()).toBe(true); const convertedBody = await converted.json();
  const replay = await request.post(`/api/quotes/${replacement.id}/convert`, { headers });
  expect(replay.ok()).toBe(true); expect((await replay.json()).order.id).toBe(convertedBody.order.id);
  await page.reload(); await openTabByLabel(page, 'Quotes & Orders');
  await page.getByRole('button', { name: `View details for order #${convertedBody.order.orderNumber}`, exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('₹303.05'); await expect(page.getByRole('dialog')).toContainText('From quote');
  expect(data().orders?.filter(row => row.quoteId === replacement.id)).toHaveLength(1);
  await page.screenshot({ path: `${proof}/week-three-converted-order.png`, fullPage: true });
});

test('fractional order can be created through the form and saved without quantity rounding', async ({ page }) => {
  await loginDemo(page); await openTabByLabel(page, 'Quotes & Orders');
  await page.getByRole('button', { name: 'New order', exact: true }).click();
  await page.locator('#create-product').fill('Fractional thread'); await page.locator('#create-qty').fill('0.3'); await page.locator('#create-price').fill('100');
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/orders') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create order', exact: true }).click(); const response = await responsePromise;
  expect(response.ok()).toBe(true); const order: Order = await response.json(); expect(order.lineItems[0].quantity).toBe(0.3); expect(order.grandTotal).toBe(30);
  await page.getByRole('button', { name: `View details for order #${order.orderNumber}`, exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('0.3'); await expect(page.getByRole('dialog')).toContainText('₹30.00');
  const shipped = await page.request.post(`/api/orders/${order.id}/status`, { headers, data: { toStatus: 'partial_shipped', shippedQuantityByLine: { [order.lineItems[0].id]: 0.1 } } });
  expect(shipped.ok()).toBe(true);
  const cancelled = await page.request.post(`/api/orders/${order.id}/cancel`, { headers, data: { cancelQuantitiesByLine: { [order.lineItems[0].id]: 0.2 }, reason: 'Remaining quantity cancelled' } });
  expect(cancelled.ok()).toBe(true); const saved: Order = await cancelled.json(); expect(saved.grandTotal).toBe(10);
  await page.reload(); await openTabByLabel(page, 'Quotes & Orders'); await page.getByRole('button', { name: `View details for order #${order.orderNumber}`, exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('₹10.00'); await expect(page.getByRole('dialog')).toContainText('0.1 remaining');
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Cancel item quantities', exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Close panel', exact: true }).click();
  await page.getByRole('button', { name: `More actions for order #${order.orderNumber}`, exact: true }).click();
  await expect(page.getByRole('menuitem', { name: 'Cancel order', exact: true })).toHaveCount(0);
});

test('support refuses another customer order and retains the correct link through UI resolution and reopening', async ({ page, request }) => {
  const [buyerA, buyerB] = data().leads;
  const orderResponse = await request.post('/api/orders', { headers, data: { leadId: buyerB.id, lineItems: [{ productName: 'Support thread', quantity: 1, unitPrice: 500 }] } });
  expect(orderResponse.ok()).toBe(true); const order: Order = await orderResponse.json();
  const payload = { subject: 'Week Three linked complaint', description: 'Check the supplied thread', type: 'complaint', priority: 'high', orderId: order.id };
  const refused = await request.post('/api/tickets', { headers, data: { ...payload, leadId: buyerA.id } }); expect(refused.status()).toBe(400);
  const created = await request.post('/api/tickets', { headers, data: { ...payload, leadId: buyerB.id } }); expect(created.ok()).toBe(true); const ticket = await created.json();
  await loginDemo(page); await openTabByLabel(page, 'Tickets');
  await page.locator("li").filter({ hasText: payload.subject }).getByRole("button").click();
  await expect(page.getByText(`Order #${order.orderNumber}`, { exact: true })).toBeVisible();
  const resolvedResponse = page.waitForResponse(r => r.url().endsWith(`/api/tickets/${ticket.id}/status`) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Mark resolved', exact: true }).click();
  await page.getByLabel('Outcome and follow-up').fill('Issue corrected; follow-up remains reviewed.');
  await page.getByRole('button', { name: 'Save resolution', exact: true }).click();
  expect((await resolvedResponse).ok()).toBe(true);
  await expect(page.getByRole('button', { name: 'Reopen', exact: true })).toBeVisible({ timeout: 30_000 });
  expect(data().tickets?.find(row => row.id === ticket.id)?.status).toBe('resolved');
  const reopenedResponse = page.waitForResponse(r => r.url().endsWith(`/api/tickets/${ticket.id}/status`) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Reopen', exact: true }).click();
  await page.getByLabel('Reason for reopening').fill('Customer needs another check.');
  await page.getByRole('button', { name: 'Confirm reopen', exact: true }).click(); expect((await reopenedResponse).ok()).toBe(true);
  await expect(page.getByRole('button', { name: 'Start working', exact: true })).toBeVisible({ timeout: 30_000 });
  await expect(page.getByLabel(`Ticket #${ticket.ticketNumber}`).getByText('Resolved', { exact: true })).toBeVisible({ timeout: 30_000 });
  expect(data().ticketEvents?.filter(event => event.ticketId === ticket.id && event.eventType === 'reopened')).toHaveLength(1);
  await page.reload(); await openTabByLabel(page, 'Tickets'); await page.locator("li").filter({ hasText: payload.subject }).getByRole("button").click();
  await expect(page.getByText(`Order #${order.orderNumber}`, { exact: true })).toBeVisible();
  expect(data().tickets?.find(row => row.id === ticket.id)?.status).toBe('reopened');
  await expect(page.getByLabel(`Ticket #${ticket.ticketNumber}`).getByText('Resolved', { exact: true })).toBeVisible({ timeout: 30_000 });
  await expect(page.getByLabel(`Ticket #${ticket.ticketNumber}`)).toContainText('Created manually.');
  await page.screenshot({ path: `${proof}/week-three-support.png`, fullPage: true });
});

test('quote PDF contains the saved customer, precise amounts and validity without making a customer send', async ({ request }) => {
  const response = await request.post('/api/quotes', { headers, data: { leadId: data().leads[0].id, currencyCode: 'USD', lineItems: [{ productName: 'PDF precision thread', quantity: 2, unitPrice: 12.345 }], validityNote: 'Seven days' } });
  expect(response.ok()).toBe(true); const q: Quote = await response.json();
  const before = data();
  const generated = await request.post(`/api/quotes/${q.id}/generate-pdf`, { headers }); expect(generated.ok()).toBe(true); const media = await generated.json();
  const download = await request.get(media.url, { headers }); expect(download.ok()).toBe(true);
  const buffer = await download.body(); const text = buffer.toString('latin1');
  expect(text.startsWith('%PDF-')).toBe(true); expect(text).toContain('PDF precision thread'); expect(text).toContain('USD 12.345'); expect(text).toContain('USD 24.69'); expect(text).toContain('Seven days'); expect(text).not.toContain('undefined');
  fs.writeFileSync(`${proof}/week-three-quote.pdf`, buffer);
  expect(data().outreachActivities.filter(row => row.direction === "outbound" && ["sent", "sent_api", "sent_manual"].includes(row.status)).length).toBe(before.outreachActivities.filter(row => row.direction === "outbound" && ["sent", "sent_api", "sent_manual"].includes(row.status)).length);
});
