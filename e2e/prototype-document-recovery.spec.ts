import { test, expect } from '@playwright/test';
import { expectAppShell } from './helpers/login';
import { openTabByLabel } from './helpers/nav';
test('missing document model asks owner to act and leaves knowledge untouched', async ({ page }) => {
  await page.goto('/signup');
  await page.getByLabel('Your name', { exact: true }).fill('Document proof owner');
  await page.getByLabel('Email', { exact: true }).fill('document-proof@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('Synthetic-document-proof-password!');
  await page.getByLabel(/Business name/).fill('Document proof company');
  await page.getByRole('button', { name: /Create|Sign up/i }).click();
  await expect(page.getByText('Request processed', { exact: true })).toBeVisible();
  await page.goto('/');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('document-proof@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('Synthetic-document-proof-password!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expectAppShell(page);
  const reply = await page.request.post('/api/documents/process', { headers: { origin: new URL(page.url()).origin }, data: { title: 'Synthetic supplier FAQ', documentType: 'faq', contentText: 'Our company supplies modular product sample kits. Please ask the owner for prices and delivery details.' } });
  expect(reply.status()).toBe(400);
  const result = await reply.json();
  expect(result.error.code).toBe('NEEDS_ACTION');
  expect(result.error.message).toContain('Configure and test a real Daily Workhorse model');
  await openTabByLabel(page, 'Onboarding');
  await page.getByRole('button', { name: 'Advanced: paste text manually', exact: true }).click();
  await page.getByRole('textbox', { name: 'Paste text', exact: true }).fill('Our company supplies modular product sample kits. Please ask the owner for prices and delivery details.');
  let release!: () => void;
  let captured!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  const started = new Promise<void>(resolve => { captured = resolve; });
  await page.route('**/api/onboarding/extract-company-knowledge', async route => {
    captured();
    await held;
    await route.continue();
  });
  const inactivePoll = page.waitForResponse(async response => response.url().endsWith('/api/extraction-runs/active') && response.ok() && !(await response.json()).active);
  const extractionReply = page.waitForResponse(response => response.url().endsWith('/api/onboarding/extract-company-knowledge') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Extract Company Knowledge', exact: true }).click();
  await started;
  await inactivePoll;
  await expect(page.getByRole('button', { name: 'Extraction running...', exact: true })).toBeDisabled();
  release();
  expect((await extractionReply).status()).toBe(400);
  await expect(page.getByText(/Configure and test a real Daily Workhorse model/).first()).toBeVisible({ timeout: 60000 });
  await expect(page.getByRole('button', { name: 'Extract Company Knowledge', exact: true })).toBeEnabled();
  await expect(page.getByText('No company answers were added. Connect a working AI model in AI Settings, then try again.', { exact: true })).toBeVisible();
  await expect(page.getByText(/This extraction completed using sample\/mock answers/)).toHaveCount(0);
  await page.screenshot({ path: 'docs/system-workflow/readiness-proof/cleanup-document-owner-action.png', fullPage: true });
});
