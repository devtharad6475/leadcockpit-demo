import './_helpers/isolate-standalone';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { buildPdfFromLines, sanitizePdfText } from '@/lib/pdf-writer';
import { generateQuotePdf } from '@/services/QuotePdfService';
import { createJsonRepos } from './_helpers/provider';
import { inspectPdf } from './_helpers/pdf-inspection';
import { extractPdfText } from '@/lib/pdf-text';
async function main() {
  const folder=path.join(process.cwd(),'public','fonts','pdf');
  const manifest=JSON.parse(fs.readFileSync(path.join(folder,'SOURCES.json'),'utf8').replace(/^\uFEFF/,''));
  assert(manifest.commit === 'ffebf8c1ee449e544955a7e813c54f9b73848eac');
  for(const font of manifest.fonts) assert.equal(createHash('sha256').update(fs.readFileSync(path.join(folder,font.file))).digest('hex'),font.sha256);
  assert.equal(createHash('sha256').update(fs.readFileSync(path.join(folder,'OFL.txt'))).digest('hex'),manifest.licenseSha256);
  assert(fs.readFileSync(path.join(folder,'OFL.txt'),'utf8').includes('SIL OPEN FONT LICENSE'));
  console.log('PASS A: pinned redistributable font bytes and license hashes match');
  const hindi='श्री व्यापार क्षेत्र में गुणवत्ता और विशेष उत्पाद';
  const gujarati='ગુજરાતી વેપાર અને ગુણવત્તા';
  const latin='Café Müller – résumé €125.00 ₹9,876.54';
  assert.equal(sanitizePdfText(latin),latin);
  const pdf=await buildPdfFromLines(['# Quotation / प्रस्ताव / ભાવપત્રક','Prepared for: '+hindi,'Prepared by: '+gujarati,latin,'## Specifications / विशेष विवरण',hindi,gujarati,'## Long reference','SKU'+('W'.repeat(280)),...Array.from({length:95},(_,i)=>`Clause ${i+1}: ${hindi} / ${gujarati}`),'FINAL DOCUMENT END']);
  const proof=path.join(process.cwd(),'docs','system-workflow','readiness-proof');
  fs.mkdirSync(proof, { recursive: true });
  fs.writeFileSync(path.join(proof,'document-multilingual-layout.pdf'),pdf);
  const inspected=await inspectPdf(pdf);
  // PDF.js ordinary text extraction ignores ActualText and returns shaped Indic
  // visual order. Its parsed accessibility tree preserves exact logical text.
  for(const phrase of [hindi,gujarati,latin,'FINAL DOCUMENT END']) assert(inspected.accessibleText.includes(phrase),`Missing accessible text: ${phrase}`);
  for(const phrase of [gujarati,latin,'FINAL DOCUMENT END']) assert(inspected.text.includes(phrase),`Missing ordinary parsed text: ${phrase}`);
  const uploadedText=await extractPdfText(pdf);
  for(const phrase of [hindi,gujarati,latin,'FINAL DOCUMENT END']) assert(uploadedText.includes(phrase),`Reupload lost exact logical text: ${phrase}`);
  assert(inspected.pages.length>=3);
  for(const page of inspected.pages) for(const item of page.items.filter(item=>item.text.trim())) assert(item.x>=47.8 && item.x+item.width<=547.6 && item.y>=47.8 && item.y+item.height<=794.3,`Overflow: ${JSON.stringify(item)}`);
  console.log('PASS B: parsed accessibility text preserves exact languages; ordinary Latin/Gujarati text and multipage geometry survive');
  await assert.rejects(()=>buildPdfFromLines(['Unsupported Chinese customer: 客户']),/not supported yet/);
  await assert.rejects(()=>buildPdfFromLines(['Unsupported emoji: 🚀']),/not supported yet/);
  console.log('PASS C: unsupported glyphs fail explicitly instead of deleting text');
  const empty = await inspectPdf(await buildPdfFromLines([]));
  assert.equal(empty.pages.length,1);
  assert(empty.text.includes('Document'));
  const conjunctToken='क्षेत्रविशेष'.repeat(65);
  const conjuncts=await inspectPdf(await buildPdfFromLines([conjunctToken]));
  assert(conjuncts.accessibleText.replace(/\s/g,'').includes(conjunctToken));
  for(const page of conjuncts.pages) for(const item of page.items.filter(item=>item.text.trim())) assert(item.x>=47.8 && item.x+item.width<=547.6,`Indic token outside margin: ${JSON.stringify(item)}`);
  console.log('PASS C2: empty documents remain readable and oversized Indic tokens preserve graphemes');
  const repos=await createJsonRepos(); const workspaceId='ws_pdf_unsupported';
  await repos.workspace.create({id:workspaceId,name:'PDF rejection fixture',status:'active'});
  const lead=await repos.lead.createLead({workspaceId,companyName:'Fixture Customer',source:'manual',status:'approved',reviewStatus:'approved',enrichmentStatus:'completed',doNotContact:false,consentStatus:'none'});
  const quote=await repos.quote.create({workspaceId,leadId:lead.id,status:'draft',currencyCode:'INR',grandTotal:25,lineItems:[{id:'unsupported-item',productName:'客户',quantity:1,unit:'item',unitPrice:25,currencyCode:'INR',lineTotal:25}]});
  const before=await repos.mediaCatalog.listByWorkspace(workspaceId);
  await assert.rejects(()=>generateQuotePdf({workspaceId,quoteId:quote.id},repos),/not supported yet/);
  assert.equal((await repos.mediaCatalog.listByWorkspace(workspaceId)).length,before.length);
  assert.equal((await repos.quote.getById(workspaceId,quote.id))?.lineItems[0].productName,'客户');
  console.log('PASS D: failed generation leaves quote unchanged and creates no media record');
  console.log('document-language-layout: 5 passed, 0 failed');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
