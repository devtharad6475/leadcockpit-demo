/**
 * WALK THE SALE PATH — the front-door run (MASTER-PLAN stage 1/2, A8 + A9).
 *
 * ── WHY THIS IS NOT A GOLDEN ────────────────────────────────────────────────
 * A golden asserts and ABORTS at the first failure. That is right for a
 * regression gate and wrong here: the point of this run is to find EVERY place
 * the product breaks for a brand-new customer, in one pass, so the list can be
 * worked through. So every step records its outcome and the walk continues.
 *
 * A step that cannot run because an earlier step failed is reported BLOCKED,
 * never PASS and never FAIL — "we never found out" is a third answer, and
 * collapsing it into either of the other two is how a walk starts lying.
 *
 * ── WHAT IT DRIVES ──────────────────────────────────────────────────────────
 * The seven steps a real customer walks, taken from the product's own
 * navigation (src/app/page.tsx `tabs`), not invented for the test:
 *
 *   1 sign up                       POST /auth/signup
 *   2 tell it about the business    POST/GET /business-profile
 *   3 teach it                      /knowledge/*
 *   4 who to target                 /icp/*
 *   5 find leads                    /campaigns, /leads/*
 *   6 approve them                  /leads/:id/approve, /leads/:id/reject
 *   7 sell                          /messages/generate, /quotes
 *
 * TWO tenants are walked, not one, because a single tenant cannot demonstrate
 * isolation (A9). After both exist, each one is pointed at the other's records
 * and must be refused.
 *
 * ── CREDENTIALS ─────────────────────────────────────────────────────────────
 * The two fixture owners get passwords generated by `randomBytes` inside this
 * process. They are never printed, never written to a file, and never leave
 * this run -- the session cookie from the signup response is what the walk
 * uses. Same rule the S16 runbook set.
 *
 * ── SAFETY (N-SAFETY-1) ─────────────────────────────────────────────────────
 * Every address is under RFC 2606 `.example`, which ICANN guarantees is never
 * delegated. Every phone is `+91 00000 000NN`; a real Indian mobile subscriber
 * number never begins with 0. The fixtures are unroutable BY CONSTRUCTION, so
 * nothing here can be messaged by accident even if outreach fired for real.
 *
 * ── AFTERWARDS ──────────────────────────────────────────────────────────────
 * The workspaces this creates are REAL rows in the dev database. Either add
 * them to `.leadgen-data/keep-workspaces.json` or reap them, or CASE 10 of
 * golden-unroutable-contacts will correctly call them residue.
 *
 * Usage:  npx tsx scripts/walk-the-sale-path.ts [--base http://127.0.0.1:3011]
 */
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";

const BASE = (() => {
  const i = process.argv.indexOf("--base");
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : "http://127.0.0.1:3011";
})();

const STAMP = Date.now();
const REPORT = path.join(process.cwd(), ".leadgen-data", `walk-${STAMP}.json`);

type Outcome = "PASS" | "FAIL" | "BLOCKED";
type Step = {
  n: string;
  tenant: string;
  outcome: Outcome;
  status?: number;
  detail: string;
  ms: number;
};
const steps: Step[] = [];

function record(s: Step) {
  steps.push(s);
  const mark = s.outcome === "PASS" ? "PASS " : s.outcome === "FAIL" ? "FAIL " : "BLOCK";
  const code = s.status === undefined ? "   " : String(s.status).padStart(3);
  console.log(`  ${mark} ${code}  ${s.tenant.padEnd(9)} ${s.n}`);
  if (s.outcome !== "PASS") console.log(`         ${s.detail}`);
}

/** A tenant's live session. `cookie` is the only credential the walk carries. */
type Tenant = {
  key: string;
  email: string;
  business: string;
  /** Never printed. Never persisted. */
  password: string;
  cookie: string;
  workspaceId: string;
  ids: Record<string, string>;
};

function newTenant(key: string, business: string): Tenant {
  return {
    key,
    // Stamped, because signup enforces one workspace per email globally: a
    // second run with a fixed address would fail at step 1 and report a
    // product bug that is really just the first run still sitting there.
    email: `owner+${STAMP}@${key}.example`,
    business,
    // 32 URL-safe chars of real entropy. Not printed anywhere, including on
    // failure -- an error path that dumps the request body is exactly how a
    // credential ends up in a log.
    password: randomBytes(24).toString("base64url"),
    cookie: "",
    workspaceId: "",
    ids: {},
  };
}

type Res = { status: number; body: any; raw: string };

async function req(t: Tenant | null, method: string, p: string, body?: unknown): Promise<Res> {
  // Origin, because a browser always sends one. Without it `isCsrfSafe` refuses
  // every state-changing request in production mode -- correctly, since a real
  // browser cannot omit it. The first run of this walk left it off and read the
  // resulting four 403s as product bugs; they were bugs in the walk. Worse, the
  // cross-tenant probes then "passed" because the write was refused -- refused
  // by the CSRF gate, having never reached the tenant check at all.
  const headers: Record<string, string> = { "content-type": "application/json", origin: BASE };
  if (t?.cookie) headers.cookie = t.cookie;
  const res = await fetch(`${BASE}/api/${p}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  // Capture the Set-Cookie on the way past; signup and login both mint one.
  const setCookie = res.headers.get("set-cookie");
  if (t && setCookie) t.cookie = setCookie.split(";")[0];
  const raw = await res.text();
  let parsed: any = null;
  try {
    parsed = JSON.parse(raw);
  } catch {
    /* an HTML error page is itself a finding; `raw` keeps it */
  }
  return { status: res.status, body: parsed, raw };
}

/** Short, safe description of what came back. Never echoes a request body. */
function why(r: Res): string {
  if (r.body?.error?.message) return `${r.body.error.code ?? "error"}: ${r.body.error.message}`;
  if (r.body?.error) return String(JSON.stringify(r.body.error)).slice(0, 200);
  if (!r.body) return `non-JSON response (${r.raw.slice(0, 120).replace(/\s+/g, " ")})`;
  return JSON.stringify(r.body).slice(0, 200);
}

/**
 * Run one step. `fn` returns true for pass, or a string explaining the break.
 * A throw is caught and recorded -- a walk that dies on an unexpected
 * exception tells you about one break instead of all of them.
 */
async function step(
  n: string,
  t: Tenant,
  precondition: boolean,
  fn: () => Promise<true | string>,
): Promise<boolean> {
  const t0 = Date.now();
  if (!precondition) {
    record({ n, tenant: t.key, outcome: "BLOCKED", detail: "an earlier step it depends on failed", ms: 0 });
    return false;
  }
  try {
    const r = await fn();
    const ms = Date.now() - t0;
    if (r === true) {
      record({ n, tenant: t.key, outcome: "PASS", detail: "", ms });
      return true;
    }
    // A step may discover it could not actually test what it set out to test.
    // That is BLOCKED, not FAIL and emphatically not PASS -- see the cross-
    // tenant probes, where a request refused by the CSRF gate never reached
    // the tenant check and therefore proves nothing about the boundary.
    if (r.startsWith("BLOCKED:")) {
      record({ n, tenant: t.key, outcome: "BLOCKED", detail: r.slice(8).trim(), ms });
      return false;
    }
    record({ n, tenant: t.key, outcome: "FAIL", detail: r, ms });
    return false;
  } catch (e) {
    record({
      n,
      tenant: t.key,
      outcome: "FAIL",
      detail: `threw: ${(e as Error).message}`,
      ms: Date.now() - t0,
    });
    return false;
  }
}

async function walk(t: Tenant) {
  console.log(`\n── ${t.key} (${t.business}) ─────────────────────────────`);

  // ── STEP 1 — sign up ──────────────────────────────────────────────────────
  const signedUp = await step("1 sign up", t, true, async () => {
    const r = await req(t, "POST", "auth/signup", {
      email: t.email,
      password: t.password,
      name: "Priya Raman",
      businessName: t.business,
    });
    if (r.status !== 200) return `signup returned ${r.status} — ${why(r)}`;
    const ws = r.body?.data?.user?.workspaceId ?? r.body?.user?.workspaceId;
    if (!ws) return `signup returned 200 but no workspaceId in the body — ${why(r)}`;
    t.workspaceId = ws;
    if (!t.cookie) return "signup returned 200 but set no session cookie — a new customer would be signed up and immediately locked out";
    return true;
  });

  await step("1b session is real (GET /auth/me)", t, signedUp, async () => {
    const r = await req(t, "GET", "auth/me");
    if (r.status !== 200) return `/auth/me returned ${r.status} with the signup cookie — ${why(r)}`;
    const email = r.body?.data?.user?.email ?? r.body?.user?.email;
    if (email !== t.email) return `/auth/me came back as "${email}", expected "${t.email}"`;
    return true;
  });

  // ── STEP 2 — tell it about the business ───────────────────────────────────
  const profiled = await step("2 save the business profile", t, signedUp, async () => {
    const r = await req(t, "POST", "business-profile", {
      workspaceId: t.workspaceId,
      companyName: t.business,
      website: `https://${t.key}.example`,
      industry: "Industrial equipment",
      description: `${t.business} supplies industrial equipment to plants across western India.`,
      contactEmail: `sales@${t.key}.example`,
      contactPhone: "+91 00000 00011",
    });
    if (r.status !== 200 && r.status !== 201) return `saving the profile returned ${r.status} — ${why(r)}`;
    return true;
  });

  await step("2b the profile reads back", t, profiled, async () => {
    const r = await req(t, "GET", "business-profile");
    if (r.status !== 200) return `reading the profile back returned ${r.status} — ${why(r)}`;
    const got = JSON.stringify(r.body ?? {});
    if (!got.includes(t.business)) {
      return `the profile saved but did not read back — "${t.business}" is absent from the response`;
    }
    return true;
  });

  // ── STEP 3 — teach it ─────────────────────────────────────────────────────
  await step("3 the knowledge base answers", t, signedUp, async () => {
    const r = await req(t, "GET", "knowledge/essential-questions");
    if (r.status !== 200) return `the knowledge screen returned ${r.status} — ${why(r)}`;
    return true;
  });

  // ── STEP 4 — who to target ────────────────────────────────────────────────
  const icpListed = await step("4 the ideal-customer screen answers", t, signedUp, async () => {
    const r = await req(t, "GET", "icp");
    if (r.status !== 200) return `the ideal-customer screen returned ${r.status} — ${why(r)}`;
    return true;
  });

  // ── STEP 5 — find leads ───────────────────────────────────────────────────
  const gotLead = await step("5 add a lead by hand", t, signedUp, async () => {
    const r = await req(t, "POST", "leads/manual", {
      workspaceId: t.workspaceId,
      companyName: `${t.business} prospect one`,
      email: `buyer@prospect-${t.key}.example`,
      phone: "+91 00000 00021",
      contactName: "Anil Deshpande",
    });
    if (r.status !== 200 && r.status !== 201) return `adding a lead returned ${r.status} — ${why(r)}`;
    const id = r.body?.data?.id ?? r.body?.data?.lead?.id ?? r.body?.lead?.id ?? r.body?.id;
    if (!id) return `the lead saved (${r.status}) but the response carried no id — ${why(r)}`;
    t.ids.lead = id;
    return true;
  });

  await step("5b the lead is in the list", t, gotLead, async () => {
    const r = await req(t, "GET", "leads");
    if (r.status !== 200) return `the leads list returned ${r.status} — ${why(r)}`;
    if (!JSON.stringify(r.body ?? {}).includes(t.ids.lead)) {
      return `the lead saved but is not in this workspace's list — the operator would not see it`;
    }
    return true;
  });

  // ── STEP 6 — approve it ───────────────────────────────────────────────────
  await step("6 approve the lead", t, gotLead, async () => {
    const r = await req(t, "POST", `leads/${t.ids.lead}/approve`, { workspaceId: t.workspaceId });
    if (r.status !== 200) return `approving returned ${r.status} — ${why(r)}`;
    return true;
  });

  // ── STEP 7 — sell ─────────────────────────────────────────────────────────
  await step("7 the quotes screen answers", t, signedUp, async () => {
    const r = await req(t, "GET", "quotes/list");
    if (r.status !== 200) return `the quotes screen returned ${r.status} — ${why(r)}`;
    return true;
  });
}

/**
 * A9 — the boundary. Each tenant is pointed at the other's records and must be
 * refused. A 200 here is the most serious finding this walk can produce: it
 * means one paying customer can read another's pipeline.
 */
/**
 * Was this refusal the TENANT boundary doing its job, or something upstream
 * that stopped the request before the boundary was ever consulted?
 *
 * Only the first proves anything. A CSRF rejection, a rate limit or a 500 all
 * produce a non-200 that a careless check would read as "isolation works".
 */
function refusalProvesTheBoundary(r: Res): true | string {
  const code = r.body?.error?.code;
  if (code === "CSRF_REJECTED") {
    return "BLOCKED: refused by the CSRF gate before the tenant check ran — this proves nothing about isolation";
  }
  if (r.status === 429) return "BLOCKED: rate-limited before the tenant check ran";
  if (r.status >= 500) return `the server errored (${r.status}) instead of refusing — ${why(r)}`;
  if (r.status === 401) return `answered 401 (not signed in) rather than refusing this tenant — ${why(r)}`;
  if (r.status === 403 || r.status === 404) return true;
  return `refused with an unexpected ${r.status} — ${why(r)}`;
}

async function crossTenant(a: Tenant, b: Tenant) {
  console.log(`\n── the boundary: ${a.key} reaching for ${b.key} ──────────`);

  const both = Boolean(a.cookie && b.cookie);

  await step(`X1 read ${b.key}'s lead`, a, both && Boolean(b.ids.lead), async () => {
    const r = await req(a, "GET", `leads/${b.ids.lead}`);
    if (r.status === 200) {
      const leaked = JSON.stringify(r.body ?? {});
      if (leaked.includes(b.business) || leaked.includes(b.ids.lead)) {
        return `LEAK — ${a.key} read ${b.key}'s lead and got 200 with its data back`;
      }
      return `${a.key} got 200 reading ${b.key}'s lead (body looks empty, but the refusal should be explicit)`;
    }
    return refusalProvesTheBoundary(r);
  });

  await step(`X2 approve ${b.key}'s lead`, a, both && Boolean(b.ids.lead), async () => {
    const r = await req(a, "POST", `leads/${b.ids.lead}/approve`, { workspaceId: b.workspaceId });
    if (r.status === 200) return `LEAK — ${a.key} approved a lead belonging to ${b.key}`;
    return refusalProvesTheBoundary(r);
  });

  await step(`X3 write into ${b.key}'s workspace`, a, both, async () => {
    const r = await req(a, "POST", "leads/manual", {
      workspaceId: b.workspaceId,
      companyName: "cross-tenant probe",
      email: `probe@cross-${a.key}.example`,
      phone: "+91 00000 00031",
    });
    if (r.status === 200 || r.status === 201) {
      return `LEAK — ${a.key} created a lead inside ${b.key}'s workspace by asking for it in the body`;
    }
    return refusalProvesTheBoundary(r);
  });
}

let serverAuthMode: string | null = null;

async function main() {
  console.log(`\nWALKING THE SALE PATH against ${BASE}`);
  console.log(`auth mode: ${process.env.AUTH_MODE ?? "(unset — this run is not production mode)"}\n`);

  const health = await fetch(`${BASE}/api/health`).catch(() => null);
  if (!health) {
    console.error(`\nnothing is listening on ${BASE}. Start the production server first:`);
    console.error(`  AUTH_MODE=production npx next start -p 3011\n`);
    process.exitCode = 2;
    return;
  }

  // Ask the SERVER what mode it is in. Reading process.env here would describe
  // this script, which is not the thing being walked.
  const healthBody = (await health.clone().json().catch(() => null)) as
    | { authMode?: string; persistenceProvider?: string }
    | null;
  serverAuthMode = healthBody?.authMode ?? null;
  console.log(
    `server: authMode=${serverAuthMode ?? "unknown"} storage=${healthBody?.persistenceProvider ?? "unknown"}`,
  );
  if (serverAuthMode !== "production") {
    console.log(
      "  NOTE: this server is NOT in production auth mode, so the tenant boundary\n" +
        "  probes below prove less than they appear to. Treat their passes as weak.",
    );
  }

  const acme = newTenant("acme-pipes", "Acme Pipes and Fittings");
  const borealis = newTenant("borealis-chem", "Borealis Chemicals");

  await walk(acme);
  await walk(borealis);
  await crossTenant(acme, borealis);
  await crossTenant(borealis, acme);

  const pass = steps.filter((s) => s.outcome === "PASS").length;
  const fail = steps.filter((s) => s.outcome === "FAIL").length;
  const blocked = steps.filter((s) => s.outcome === "BLOCKED").length;

  console.log(`\n═══ WALK COMPLETE ═══`);
  console.log(`  ${pass} worked · ${fail} broke · ${blocked} never got the chance`);
  if (fail) {
    console.log(`\nWHAT BROKE:`);
    for (const s of steps.filter((x) => x.outcome === "FAIL")) {
      console.log(`  - [${s.tenant}] ${s.n}\n      ${s.detail}`);
    }
  }

  writeFileSync(
    REPORT,
    JSON.stringify(
      {
        at: new Date().toISOString(),
        base: BASE,
        authMode: serverAuthMode,
        workspaces: { [acme.key]: acme.workspaceId, [borealis.key]: borealis.workspaceId },
        totals: { pass, fail, blocked },
        steps,
      },
      null,
      2,
    ),
  );
  console.log(`\nreport: ${path.relative(process.cwd(), REPORT)}`);
  if (acme.workspaceId || borealis.workspaceId) {
    console.log(`\nthese workspaces are now REAL rows in the database:`);
    for (const w of [acme, borealis]) if (w.workspaceId) console.log(`  ${w.workspaceId}`);
    console.log(`add them to .leadgen-data/keep-workspaces.json or reap them, or CASE 10 will`);
    console.log(`correctly report them as residue.`);
  }

  // The walk itself succeeded if it RAN. Breaks are its output, not its failure.
  process.exitCode = 0;
}

main().catch((e) => {
  console.error(`the walk crashed: ${(e as Error).message}`);
  process.exitCode = 1;
});
